/**
 * Правила ника на сайте — одни на всех, кто его меняет или проверяет.
 *
 * «Ё» и «ё» стоят в наборе отдельно: в кодировке они лежат вне диапазона А-Я и
 * а-я, и правило без них молча отказывало Петру, Алёне и Бьёрну — на этом уже
 * обжигались в прежнем портале.
 *
 * Пробел и дефис разрешены: «Бьёрн Кузнец» — обычное имя, а не попытка что-то
 * сломать. А вот по краям их нет: ник с пробелом на конце в списке выглядит
 * опечаткой, и два таких ника не отличить друг от друга.
 */
const NICKNAME_RE = /^[A-Za-zА-Яа-яЁё0-9](?:[A-Za-zА-Яа-яЁё0-9 _-]{1,18}[A-Za-zА-Яа-яЁё0-9])$/;

const MIN = 3;
const MAX = 20;

/**
 * Возвращает текст ошибки или null, если ник годится. Текст пишется игроку,
 * поэтому объясняет, что не так, а не «невалидное значение».
 */
function nicknameError(raw) {
  const name = String(raw ?? '').trim();
  if (!name) return 'Ник не может быть пустым';
  // Считаем по символам, а не по длине строки: эмодзи и буквы с точками
  // занимают в строке больше одной позиции, а на глаз это один знак.
  const length = [...name].length;
  if (length < MIN) return `Ник короче ${MIN} символов`;
  if (length > MAX) return `Ник длиннее ${MAX} символов`;
  if (name.includes('  ')) return 'В нике два пробела подряд';
  if (!NICKNAME_RE.test(name)) {
    return 'В нике можно: буквы, цифры, пробел, дефис и подчёркивание';
  }
  return null;
}

module.exports = { nicknameError, NICKNAME_MIN: MIN, NICKNAME_MAX: MAX };
